# Q3. Program to find quotient and remainder of two numbers.

# Take input from user.

num1 = int(input('Enter the Divident value:'))
num2 = int(input('Enter the Divisor value'))

# formula for the quotient and remainder.
quotient = num1//num2
remainder = num1%num2

print('The quotient for the give value is',quotient,'and remainder is',remainder)

